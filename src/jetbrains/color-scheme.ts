import { selectionColor, terminalColors } from '../theme/colors.ts'
import type { IThemePalette } from '../theme/types.ts'
import { escapeXml, hex } from './format.ts'

const attribute = (name: string, options: Record<string, string>) => {
  const optionTags = Object.entries(options)
    .map(([key, value]) => `<option name="${key}" value="${value}"/>`)
    .join('')

  return `    <option name="${name}"><value>${optionTags}</value></option>`
}

export const createColorSchemeXml = (palette: IThemePalette) => {
  const attributes = [
    attribute('TEXT', { FOREGROUND: hex(palette.foreground), BACKGROUND: hex(palette.surfaces.editor) }),
    attribute('DEFAULT_BLOCK_COMMENT', { FOREGROUND: hex(palette.muted), FONT_TYPE: '2' }),
    attribute('DEFAULT_BRACES', { FOREGROUND: hex(palette.foreground) }),
    attribute('DEFAULT_CLASS_NAME', { FOREGROUND: hex(palette.tertiary) }),
    attribute('DEFAULT_CONSTANT', { FOREGROUND: hex(palette.tertiary) }),
    attribute('DEFAULT_FUNCTION_CALL', { FOREGROUND: hex(palette.accent) }),
    attribute('DEFAULT_FUNCTION_DECLARATION', { FOREGROUND: hex(palette.accent) }),
    attribute('DEFAULT_IDENTIFIER', { FOREGROUND: hex(palette.foreground) }),
    attribute('DEFAULT_INSTANCE_METHOD', { FOREGROUND: hex(palette.accentAlt) }),
    attribute('DEFAULT_INVALID_STRING_ESCAPE', {
      FOREGROUND: hex(palette.error),
      EFFECT_COLOR: hex(palette.error),
      ERROR_STRIPE_COLOR: hex(palette.error)
    }),
    attribute('ERRORS_ATTRIBUTES', { EFFECT_COLOR: hex(palette.error), ERROR_STRIPE_COLOR: hex(palette.error), EFFECT_TYPE: '2' }),
    attribute('WARNING_ATTRIBUTES', { EFFECT_COLOR: hex(palette.warning), ERROR_STRIPE_COLOR: hex(palette.warning), EFFECT_TYPE: '2' }),
    attribute('DEFAULT_KEYWORD', { FOREGROUND: hex(palette.primary) }),
    attribute('DEFAULT_LINE_COMMENT', { FOREGROUND: hex(palette.muted), FONT_TYPE: '2' }),
    attribute('DEFAULT_NUMBER', { FOREGROUND: hex(palette.tertiary) }),
    attribute('DEFAULT_OPERATION_SIGN', { FOREGROUND: hex(palette.primary) }),
    attribute('DEFAULT_PARAMETER', { FOREGROUND: hex(palette.secondary) }),
    attribute('DEFAULT_STRING', { FOREGROUND: hex(palette.secondary) }),
    attribute('CONSOLE_NORMAL_OUTPUT', { FOREGROUND: hex(palette.foreground) }),
    attribute('CONSOLE_ERROR_OUTPUT', { FOREGROUND: hex(palette.error) }),
    attribute('CONSOLE_SYSTEM_OUTPUT', { FOREGROUND: hex(palette.foreground) }),
    attribute('DIFF_INSERTED', { BACKGROUND: hex(`${palette.success}22`), ERROR_STRIPE_COLOR: hex(palette.success) }),
    attribute('DIFF_DELETED', { BACKGROUND: hex(`${palette.error}22`), ERROR_STRIPE_COLOR: hex(palette.error) }),
    attribute('DIFF_MODIFIED', { BACKGROUND: hex(`${palette.warning}22`), ERROR_STRIPE_COLOR: hex(palette.warning) }),
    attribute('TEXT_SEARCH_RESULT_ATTRIBUTES', { BACKGROUND: hex(`${palette.warning}33`) })
  ].join('\n')

  const ansi = Object.entries(terminalColors(palette)).map(([key, color]) => {
    const name = key.startsWith('bright') ? `${key.slice(6).toUpperCase()}_BRIGHT` : key.toUpperCase()
    return attribute(`CONSOLE_${name}_OUTPUT`, { FOREGROUND: hex(color) })
  }).join('\n')

  return `<!-- Generated by src/jetbrains/build.ts. -->
<scheme name="${escapeXml(palette.name)}" version="142" parent_scheme="Darcula">
  <colors>
    <option name="CARET_COLOR" value="${hex(palette.primary)}"/>
    <option name="CARET_ROW_COLOR" value="${hex(palette.surfaces.lineHighlight)}"/>
    <option name="GUTTER_BACKGROUND" value="${hex(palette.surfaces.editor)}"/>
    <option name="INDENT_GUIDE" value="${hex(palette.surfaces.border)}"/>
    <option name="LINE_NUMBERS_COLOR" value="${hex(palette.muted)}"/>
    <option name="RIGHT_MARGIN_COLOR" value="${hex(palette.surfaces.border)}"/>
    <option name="SELECTION_BACKGROUND" value="${hex(selectionColor(palette))}"/>
    <option name="SELECTION_FOREGROUND" value="${hex(palette.foreground)}"/>
    <option name="CONSOLE_BACKGROUND_KEY" value="${hex(palette.surfaces.editor)}"/>
    <option name="FILESTATUS_ADDED" value="${hex(palette.success)}"/>
    <option name="FILESTATUS_MODIFIED" value="${hex(palette.warning)}"/>
    <option name="FILESTATUS_DELETED" value="${hex(palette.error)}"/>
  </colors>
  <attributes>
${attributes}
${ansi}
  </attributes>
</scheme>
`
}
